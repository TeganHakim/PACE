"""
load saved feature maps + corresponding ground-truth quality .npy maps, 
train the model from model.py, validate it, and save the best weights to checkpoints/.

this script will use ALL available feature maps generated by the feature extractor in 
training for each modality. 
"""

"""
Train RGB and IR spatial quality estimators using cached
CrossFuse deep feature maps and ground-truth 8x8 quality maps.

Run from the PACE repository root:

    python prototyping/quality_estimator/train.py
"""

from pathlib import Path

import numpy as np
import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader

from model import SpatialQualityEstimator


# ---------------------------------------------------------
# Configuration
# ---------------------------------------------------------

REPO_ROOT = Path(__file__).resolve().parents[2]
QUALITY_ROOT = Path(__file__).resolve().parent

FEATURE_ROOT = QUALITY_ROOT / "features"
DATASET_ROOT = REPO_ROOT / "processed_dataset"
CHECKPOINT_ROOT = QUALITY_ROOT / "checkpoints"

MODALITIES = ("rgb", "ir")

EPOCHS = 20
BATCH_SIZE = 4
LEARNING_RATE = 1e-3
RANDOM_SEED = 42


# ---------------------------------------------------------
# Dataset
# ---------------------------------------------------------

class QualityFeatureDataset(Dataset):
    """
    Pair saved encoder feature maps with ground-truth quality maps.

    Features:
        features/{modality}/{split}/{id}.pt

    Labels:
        processed_dataset/{split}/quality_maps/{id}_{modality}.npy
    """

    def __init__(self, modality, split):
        self.modality = modality
        self.split = split

        self.feature_dir = FEATURE_ROOT / modality / split
        self.quality_dir = DATASET_ROOT / split / "quality_maps"

        if not self.feature_dir.exists():
            raise FileNotFoundError(
                f"Feature directory not found: {self.feature_dir}"
            )

        if not self.quality_dir.exists():
            raise FileNotFoundError(
                f"Quality directory not found: {self.quality_dir}"
            )

        self.feature_paths = sorted(
            self.feature_dir.glob("*.pt")
        )

        if not self.feature_paths:
            raise ValueError(
                f"No feature files found in {self.feature_dir}"
            )

        # Validate feature/label pairing before training.
        for feature_path in self.feature_paths:
            label_path = self.quality_dir / (
                f"{feature_path.stem}_{modality}.npy"
            )

            if not label_path.exists():
                raise FileNotFoundError(
                    f"Missing quality label: {label_path}"
                )

    def __len__(self):
        return len(self.feature_paths)

    def __getitem__(self, index):
        feature_path = self.feature_paths[index]
        sample_id = feature_path.stem

        label_path = self.quality_dir / (
            f"{sample_id}_{self.modality}.npy"
        )

        # Saved as float16; train using float32.
        features = torch.load(
            feature_path,
            map_location="cpu",
            weights_only=True,
        ).float()

        quality = np.load(label_path).astype(np.float32)
        quality = torch.from_numpy(quality).unsqueeze(0)

        if quality.shape != (1, 8, 8):
            raise ValueError(
                f"Unexpected quality shape for {sample_id}: "
                f"{quality.shape}"
            )

        return features, quality


# ---------------------------------------------------------
# Device selection
# ---------------------------------------------------------

def get_device():
    if torch.cuda.is_available():
        return torch.device("cuda")

    if torch.backends.mps.is_available():
        return torch.device("mps")

    return torch.device("cpu")


# ---------------------------------------------------------
# Reproducibility
# ---------------------------------------------------------

def set_seed(seed):
    torch.manual_seed(seed)
    np.random.seed(seed)

    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


# ---------------------------------------------------------
# One epoch
# ---------------------------------------------------------

def run_epoch(model, loader, criterion, device, optimizer=None):
    """
    Run one training or validation epoch.

    If optimizer is provided, update model parameters.
    Otherwise, evaluate without gradients.
    """

    training = optimizer is not None
    model.train(training)

    total_loss = 0.0
    total_absolute_error = 0.0
    total_elements = 0

    context = torch.enable_grad() if training else torch.no_grad()

    with context:
        for features, targets in loader:
            features = features.to(device)
            targets = targets.to(device)

            predictions = model(features)
            loss = criterion(predictions, targets)

            if training:
                optimizer.zero_grad()
                loss.backward()
                optimizer.step()

            batch_elements = targets.numel()

            total_loss += loss.item() * batch_elements
            total_absolute_error += (
                torch.abs(predictions - targets).sum().item()
            )
            total_elements += batch_elements

    return {
        "mse": total_loss / total_elements,
        "mae": total_absolute_error / total_elements,
    }


# ---------------------------------------------------------
# Train one modality
# ---------------------------------------------------------

def train_modality(modality, device):
    print(f"\n{'=' * 50}")
    print(f"Training {modality.upper()} quality estimator")
    print(f"{'=' * 50}")

    train_dataset = QualityFeatureDataset(
        modality=modality,
        split="train",
    )

    val_dataset = QualityFeatureDataset(
        modality=modality,
        split="val",
    )

    train_loader = DataLoader(
        train_dataset,
        batch_size=BATCH_SIZE,
        shuffle=True,
        num_workers=0,
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=BATCH_SIZE,
        shuffle=False,
        num_workers=0,
    )

    # Infer the channel count from the saved encoder features.
    sample_features, _ = train_dataset[0]
    in_channels = sample_features.shape[0]

    model = SpatialQualityEstimator(
        in_channels=in_channels
    ).to(device)

    criterion = nn.MSELoss()
    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=LEARNING_RATE,
    )

    best_val_loss = float("inf")

    CHECKPOINT_ROOT.mkdir(
        parents=True,
        exist_ok=True,
    )

    checkpoint_path = (
        CHECKPOINT_ROOT / f"quality_{modality}.pt"
    )

    print(f"Train samples: {len(train_dataset)}")
    print(f"Val samples:   {len(val_dataset)}")
    print(f"Input channels: {in_channels}")
    print(f"Device: {device}\n")

    for epoch in range(1, EPOCHS + 1):
        train_metrics = run_epoch(
            model,
            train_loader,
            criterion,
            device,
            optimizer=optimizer,
        )

        val_metrics = run_epoch(
            model,
            val_loader,
            criterion,
            device,
        )

        print(
            f"Epoch {epoch:02d}/{EPOCHS} | "
            f"Train MSE: {train_metrics['mse']:.5f} | "
            f"Val MSE: {val_metrics['mse']:.5f} | "
            f"Val MAE: {val_metrics['mae']:.5f}"
        )

        if val_metrics["mse"] < best_val_loss:
            best_val_loss = val_metrics["mse"]

            torch.save(
                {
                    "model_state_dict": model.state_dict(),
                    "modality": modality,
                    "in_channels": in_channels,
                    "epoch": epoch,
                    "val_mse": best_val_loss,
                },
                checkpoint_path,
            )

    print(f"\nBest validation MSE: {best_val_loss:.5f}")
    print(f"Saved checkpoint: {checkpoint_path}")


# ---------------------------------------------------------
# Main
# ---------------------------------------------------------

def main():
    set_seed(RANDOM_SEED)

    device = get_device()
    print(f"Using device: {device}")

    for modality in MODALITIES:
        train_modality(modality, device)

    print("\nQuality estimator training complete.")


if __name__ == "__main__":
    main()
