
#!/usr/bin/env python3
"""Evaluate 50/50 RGB–IR addition with the pretrained CrossFuse detector.

Run from the PACE repository root:

    python baseline/addition/evaluate.py \
        --split test --max-samples 100 --device mps --warmup 10

Use --max-samples 0 for the complete test split.

Requires fused images generated by baseline/addition/fuse.py.
"""

import argparse
import csv
import importlib.util
import json
import random
import sys
import time

from collections import defaultdict
from pathlib import Path

import cv2
import numpy as np
import torch
from ultralytics.nn.tasks import DetectionModel


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
CROSSFUSE = ROOT / "baseline" / "CrossFuse"

sys.path.insert(0, str(HERE))
sys.path.insert(0, str(CROSSFUSE))

from fuse import sample_paths, read_gray, fuse_arrays


# Reuse the existing CrossFuse evaluation utilities and metric definitions.
spec = importlib.util.spec_from_file_location(
    "crossfuse_evaluation_shared",
    CROSSFUSE / "evaluate.py",
)
shared = importlib.util.module_from_spec(spec)
spec.loader.exec_module(shared)


def arguments():
    parser = argparse.ArgumentParser(description=__doc__)

    parser.add_argument(
        "--dataset-root",
        type=Path,
        default=ROOT / "processed_dataset",
    )
    parser.add_argument(
        "--split",
        choices=("train", "val", "test"),
        default="test",
    )
    parser.add_argument(
        "--max-samples",
        type=int,
        default=100,
        help="0 evaluates the entire split",
    )
    parser.add_argument(
        "--fused-dir",
        type=Path,
        default=None,
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
    )
    parser.add_argument(
        "--detector-weights",
        type=Path,
        default=(
            CROSSFUSE
            / "models"
            / "transfuse"
            / "fusetrans_epoch_28.model"
        ),
    )
    parser.add_argument(
        "--device",
        choices=("auto", "cuda", "mps", "cpu"),
        default="auto",
    )
    parser.add_argument("--image-size", type=int, default=256)
    parser.add_argument("--confidence", type=float, default=0.5)
    parser.add_argument("--nms-iou", type=float, default=0.7)
    parser.add_argument("--warmup", type=int, default=10)
    parser.add_argument("--visualizations", type=int, default=12)
    parser.add_argument("--seed", type=int, default=42)

    return parser.parse_args()


def load_detector(weights, device):
    """Extract and load only the detector from the CrossFuse checkpoint."""

    if not weights.is_file():
        raise FileNotFoundError(weights)

    checkpoint = torch.load(
        weights,
        map_location="cpu",
        weights_only=True,
    )

    if isinstance(checkpoint, dict) and "state_dict" in checkpoint:
        checkpoint = checkpoint["state_dict"]

    if isinstance(checkpoint, dict) and "model" in checkpoint:
        checkpoint = checkpoint["model"]

    if not isinstance(checkpoint, dict):
        raise TypeError("Expected a state_dict checkpoint")

    detector_weights = {
        key.removeprefix("detector."): value
        for key, value in checkpoint.items()
        if key.startswith("detector.")
    }

    if not detector_weights:
        raise RuntimeError(
            "No detector.* weights found in the checkpoint"
        )

    detector = DetectionModel(
        "yolo11n.yaml",
        ch=1,
        nc=len(shared.CLASS_TO_ID),
        verbose=False,
    ).to(device)

    detector.load_state_dict(detector_weights, strict=True)
    detector.eval().requires_grad_(False)

    return detector


def prepare_pixels(image, device):
    """Represent grayscale pixel values as integers on the device."""

    return torch.from_numpy(
        image.astype(np.int32)
    ).to(device)


def run_addition(rgb_pixels, ir_pixels):
    """Apply exact 50/50 averaging with half-up integer rounding.

    Input: two [H, W] integer tensors with values in [0, 255].
    Output: [1, 1, H, W] float32 tensor normalized to [0, 1].

    Equivalent to fuse.py's fuse_arrays() for every input pixel.
    """

    fused_pixels = (rgb_pixels + ir_pixels + 1) // 2

    return (
        fused_pixels
        .float()
        .unsqueeze(0)
        .unsqueeze(0)
        / 255.0
    )


def write_outputs(output, rows, predictions, report, latency):
    shared.json_write(output / "summary.json", report)
    shared.json_write(output / "latency.json", latency)
    shared.json_write(output / "predictions.json", predictions)
    shared.write_csv(output / "per_sample.csv", rows)


def main():
    args = arguments()

    if (
        args.max_samples < 0
        or args.warmup < 0
        or args.visualizations < 0
        or args.image_size <= 0
    ):
        raise ValueError("Invalid evaluation arguments")

    random.seed(args.seed)
    np.random.seed(args.seed)
    torch.manual_seed(args.seed)

    device = shared.device_for(args.device)

    suffix = (
        "all" if args.max_samples == 0
        else str(args.max_samples)
    )

    fused_dir = (
        args.fused_dir
        if args.fused_dir is not None
        else HERE / f"fused_{args.split}"
    )

    output = args.output or (
        HERE / "evaluation" / f"addition_{args.split}_{suffix}"
    )

    output.mkdir(parents=True, exist_ok=True)

    visualization_dir = output / "visualizations"
    if args.visualizations:
        visualization_dir.mkdir(exist_ok=True)

    pairs = sample_paths(
        args.dataset_root,
        args.split,
        args.max_samples,
    )

    # Ensure all expected images exist before loading the detector.
    for sample_id, _, _ in pairs:
        fused_path = fused_dir / f"{sample_id}.png"

        if not fused_path.is_file():
            raise FileNotFoundError(
                f"Missing fused image: {fused_path}\n"
                "Run baseline/addition/fuse.py first."
            )

    metadata = shared.read_metadata(
        args.dataset_root / "metadata.csv"
    )

    detector = load_detector(args.detector_weights, device)

    overall_metric = shared.metric_engine(device)
    subset_metrics = {
        "clean": shared.metric_engine(device),
        "degraded": shared.metric_engine(device),
    }

    rows = []
    predictions_json = []
    predictions_for_pr = []
    targets_for_pr = []
    latencies = defaultdict(list)

    print(
        f"Device: {device} | "
        f"Split: {args.split} | "
        f"Samples: {len(pairs)}"
    )

    with torch.inference_mode():

        for index, (sample_id, rgb_path, ir_path) in enumerate(pairs):

            # --------------------------------------------------
            # Load original modality images
            # --------------------------------------------------
            rgb = read_gray(rgb_path, args.image_size)
            ir = read_gray(ir_path, args.image_size)

            stored_fused = cv2.imread(
                str(fused_dir / f"{sample_id}.png"),
                cv2.IMREAD_GRAYSCALE,
            )

            # Verify the stored image matches exact addition.
            expected_fused = fuse_arrays(rgb, ir)

            if (
                stored_fused is None
                or not np.array_equal(stored_fused, expected_fused)
            ):
                raise ValueError(
                    f"50/50 fused image mismatch: {sample_id}"
                )

            # Prepare integer pixel tensors outside timing.
            rgb_pixels = prepare_pixels(rgb, device)
            ir_pixels = prepare_pixels(ir, device)

            # --------------------------------------------------
            # Load ground truth and degradation metadata
            # --------------------------------------------------
            targets = shared.load_targets(
                str(ir_path),
                str(rgb_path),
                args.image_size,
                args.image_size,
            )

            record = metadata.get(
                (args.split, sample_id),
                {},
            )

            degraded = (
                str(record.get("degraded", ""))
                .strip()
                .lower()
                in ("true", "1", "yes")
            )

            subset = (
                "degraded" if degraded
                else "clean" if record
                else "unknown"
            )

            # --------------------------------------------------
            # Warmup: same fusion + detector as evaluation
            # --------------------------------------------------
            if index == 0:
                for _ in range(args.warmup):

                    warm_fused = run_addition(
                        rgb_pixels,
                        ir_pixels,
                    )

                    _ = shared.decode(
                        detector,
                        warm_fused,
                        0.001,
                        args.nms_iou,
                    )

                shared.sync(device)

            # --------------------------------------------------
            # Stage 1: 50/50 addition fusion
            # --------------------------------------------------
            shared.sync(device)
            start = time.perf_counter()

            fused = run_addition(
                rgb_pixels,
                ir_pixels,
            )

            shared.sync(device)
            fusion_end = time.perf_counter()

            # --------------------------------------------------
            # Stage 2: YOLO11n + NMS
            # --------------------------------------------------
            pred = shared.decode(
                detector,
                fused,
                0.001,
                args.nms_iou,
            )

            shared.sync(device)
            detection_end = time.perf_counter()

            duration = {
                "fusion_ms": (
                    fusion_end - start
                ) * 1000,
                "detection_nms_ms": (
                    detection_end - fusion_end
                ) * 1000,
                "end_to_end_ms": (
                    detection_end - start
                ) * 1000,
            }

            for key, value in duration.items():
                latencies[key].append(value)

            # --------------------------------------------------
            # Detection metrics
            # --------------------------------------------------
            gt = shared.targets_to_metric_format(
                [targets],
                args.image_size,
                args.image_size,
                device,
            )[0]

            prediction_device = {
                key: value.to(device)
                for key, value in pred.items()
            }

            overall_metric.update(
                [prediction_device],
                [gt],
            )

            if subset in subset_metrics:
                subset_metrics[subset].update(
                    [prediction_device],
                    [gt],
                )

            predictions_for_pr.append(pred)

            targets_for_pr.append({
                key: value.cpu()
                for key, value in gt.items()
            })

            # --------------------------------------------------
            # Image-quality metrics
            # --------------------------------------------------
            fusion_report = shared.fusion_metrics(
                rgb,
                ir,
                expected_fused,
            )

            # --------------------------------------------------
            # Per-sample data
            # --------------------------------------------------
            row = {
                "sample_id": sample_id,
                "split": args.split,
                "subset": subset,
                "degraded": record.get("degraded", ""),
                "modality": record.get("modality", ""),
                "degradation_type": record.get(
                    "degradation_type", ""
                ),
                "severity": record.get("severity", ""),
                "num_ground_truth": len(targets),
                "num_predictions_at_confidence": sum(
                    float(score) >= args.confidence
                    for score in pred["scores"]
                ),
                **fusion_report,
                **duration,
            }

            rows.append(row)

            predictions_json.append({
                "sample_id": sample_id,
                "predictions": shared.prediction_records(pred),
                "ground_truth": [
                    {
                        "class_id": int(class_id),
                        "cx": float(cx),
                        "cy": float(cy),
                        "width": float(width),
                        "height": float(height),
                    }
                    for class_id, cx, cy, width, height in targets
                ],
            })

            # --------------------------------------------------
            # Save sample visualizations
            # --------------------------------------------------
            if index < args.visualizations:

                panel = shared.draw_panel(
                    rgb,
                    ir,
                    expected_fused,
                    pred,
                    targets,
                    args.confidence,
                )

                cv2.imwrite(
                    str(visualization_dir / f"{sample_id}.png"),
                    panel,
                )

                cv2.imwrite(
                    str(visualization_dir / f"{sample_id}_fused.png"),
                    expected_fused,
                )

            if (
                (index + 1) % 100 == 0
                or index + 1 == len(pairs)
            ):
                print(
                    f"Evaluated {index + 1}/{len(pairs)}"
                )

    # ------------------------------------------------------
    # Aggregate detection metrics
    # ------------------------------------------------------
    pr_metrics = shared.calculate_metrics(
        predictions_for_pr,
        targets_for_pr,
        confidence=args.confidence,
        iou_threshold=0.5,
    )

    overall_metrics = shared.metric_result(overall_metric)

    subsets = {}

    for name, engine in subset_metrics.items():

        indices = [
            i for i, row in enumerate(rows)
            if row["subset"] == name
        ]

        if not indices:
            continue

        subsets[name] = {
            "count": len(indices),
            **shared.metric_result(engine),
            **shared.calculate_metrics(
                [predictions_for_pr[i] for i in indices],
                [targets_for_pr[i] for i in indices],
                confidence=args.confidence,
                iou_threshold=0.5,
            ),
        }

    # ------------------------------------------------------
    # Aggregate latency
    # ------------------------------------------------------
    latency = {
        key: shared.aggregate(values)
        for key, values in latencies.items()
    }

    latency["fps_from_mean_latency"] = (
        1000.0 / latency["end_to_end_ms"]["mean"]
    )

    if device.type == "cuda":
        latency["cuda_peak_allocated_mb"] = (
            torch.cuda.max_memory_allocated(device) / 1024**2
        )

    # ------------------------------------------------------
    # Aggregate image-quality metrics
    # ------------------------------------------------------
    fusion_keys = (
        "entropy",
        "spatial_frequency",
        "average_gradient",
        "mi_rgb",
        "mi_ir",
        "mi_total",
    )

    fusion_quality = {
        key: shared.aggregate([
            row[key] for row in rows
        ])
        for key in fusion_keys
    }

    # ------------------------------------------------------
    # Build evaluation summary
    # ------------------------------------------------------
    report = {
        "configuration": {
            "split": args.split,
            "max_samples": args.max_samples,
            "samples_evaluated": len(rows),
            "device": str(device),
            "image_size": args.image_size,
            "confidence": args.confidence,
            "nms_iou": args.nms_iou,
            "seed": args.seed,
            "warmup": args.warmup,
            "detector_weights": str(
                args.detector_weights.resolve()
            ),
            "inference_path": "50/50 addition + YOLO11n",
            "fusion": "pixel-wise mean with half-up rounding",
        },
        "detection": {
            **overall_metrics,
            **pr_metrics,
        },
        "subsets": subsets,
        "fusion_quality": fusion_quality,
        "latency": latency,
        "parameters": {
            "detector": sum(
                p.numel()
                for p in detector.parameters()
            ),
        },
    }

    # ------------------------------------------------------
    # Save all evaluation artifacts
    # ------------------------------------------------------
    write_outputs(
        output,
        rows,
        predictions_json,
        report,
        latency,
    )

    shared.write_csv(
        output / "per_class.csv",
        [
            {
                "class_name": name,
                "ap50_95": value,
                "recall_100": overall_metrics.get(
                    "mar_100_per_class", {}
                ).get(name),
            }
            for name, value in overall_metrics.get(
                "map_per_class", {}
            ).items()
        ],
    )

    print(json.dumps({
        "detection": report["detection"],
        "latency": latency,
    }, indent=2))

    print(f"Evaluation complete: {output}")


if __name__ == "__main__":
    main()
